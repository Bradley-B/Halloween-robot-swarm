"""Local animation importer. Python 3.10+; standard library only."""

import argparse
import json
import os
from pathlib import Path
import re
import tempfile
import threading
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer


APP = Path(__file__).resolve().parent
ROOT = APP.parent
LIBRARY = ROOT / "server" / "animations.json"
HEADER = ROOT / "firmware" / "src" / "custom_animations.h"
MAX_BODY = 512 * 1024
MAX_PIXELS = 128 * 1024
SAVE_LOCK = threading.Lock()


def rgb332(red, green, blue):
    return (red & 0xE0) | ((green & 0xE0) >> 3) | (blue >> 6)


def builtin_animations():
    """Read the simple built-in frame declarations, without executing C++ text."""
    source = (ROOT / "firmware" / "src" / "frames.cpp").read_text(encoding="utf-8")
    palette = {"K": 0}
    for name, red, green, blue in re.findall(
        r"constexpr uint8_t (\w+) = rgb332\((\d+),\s*(\d+),\s*(\d+)\);", source
    ):
        palette[name] = rgb332(int(red), int(green), int(blue))
    pixels = {}
    for name, body in re.findall(r"const uint8_t (\w+)\[\] PROGMEM = \{(.*?)\};", source, re.S):
        tokens = [token.strip() for token in body.split(",") if token.strip()]
        if tokens and all(token in palette for token in tokens):
            pixels[name] = [palette[token] for token in tokens]
    sequences = dict(re.findall(r"const ColorFrame (\w+)\[\] PROGMEM = \{(.*?)\};", source, re.S))
    names = dict(re.findall(r'const char (\w+)\[\] PROGMEM = "([a-z0-9_-]+)";', source))
    result = []
    for name, sequence, width in re.findall(
        r"\{(\w+Name),\s*(\w+Frames),\s*sizeof\([^}]+?,\s*(MATRIX_WIDTH|MOUTH_WIDTH|0)\}", source
    ):
        if width == "0":
            continue  # The UI offers a separate off selection for each part.
        frames, durations = [], []
        for pixel_name, duration in re.findall(r"\{(\w+),\s*(\d+)\}", sequences[sequence]):
            frames.append(pixels[pixel_name])
            durations.append(int(duration))
        result.append({"name": names[name], "part": "eyes" if width == "MATRIX_WIDTH" else "mouth",
                       "frames": frames, "durations": durations, "builtin": True})
    return result


def validate_animation(value):
    if not isinstance(value, dict):
        raise ValueError("Send an animation object.")
    name, part = value.get("name"), value.get("part")
    if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_-]{0,31}", name):
        raise ValueError("Use 1–32 lowercase letters, numbers, hyphens or underscores; start with a letter.")
    if part not in ("eyes", "mouth"):
        raise ValueError("Choose eyes or mouth.")
    frames, durations = value.get("frames"), value.get("durations")
    if not isinstance(frames, list) or not 1 <= len(frames) <= 255:
        raise ValueError("An animation must contain 1–255 frames.")
    width = 13 if part == "eyes" else 26
    for frame in frames:
        if not isinstance(frame, list) or len(frame) != width * 9:
            raise ValueError(f"Each {part} frame must be exactly {width}×9 pixels.")
        if any(type(pixel) is not int or not 0 <= pixel <= 255 for pixel in frame):
            raise ValueError("Pixels must be RGB332 bytes (0–255).")
    if not isinstance(durations, list) or len(durations) != len(frames):
        raise ValueError("Each frame needs a hold time.")
    if any(type(ms) is not int or not 1 <= ms <= 65535 for ms in durations):
        raise ValueError("Frame hold times must be 1–65535 milliseconds.")
    return {"name": name, "part": part, "frames": frames, "durations": durations}


def load_library():
    values = json.loads(LIBRARY.read_text(encoding="utf-8"))
    if not isinstance(values, list):
        raise ValueError("server/animations.json must contain a list.")
    animations = [validate_animation(value) for value in values]
    reserved = {a["name"] for a in builtin_animations()} | {"off"}
    for animation in animations:
        if animation["name"] in reserved:
            raise ValueError(f"Duplicate or reserved animation name: {animation['name']}")
        reserved.add(animation["name"])
    check_budget(animations)
    return animations


def check_budget(animations):
    # Leave room in the 1 MB board's flash for code and existing assets.
    if sum(len(frame) for a in animations for frame in a["frames"]) > MAX_PIXELS:
        raise ValueError("The custom animation library exceeds the 128 KiB pixel budget. Use fewer frames.")


def render_header(animations):
    lines = ["// Generated by Animation Studio. Edit animations through the app.",
             "// Source of truth: server/animations.json", "#pragma once", ""]
    entries = []
    for index, animation in enumerate(animations):
        prefix = f"custom_{index}"
        width = 13 if animation["part"] == "eyes" else 26
        references = []
        unique = {}
        for frame in animation["frames"]:
            key = tuple(frame)
            if not any(frame):
                references.append("nullptr")
                continue
            if key not in unique:
                symbol = f"{prefix}_pixels_{len(unique)}"
                unique[key] = symbol
                lines.append(f"const uint8_t {symbol}[] PROGMEM = {{")
                for row in range(9):
                    lines.append("  " + ", ".join(f"0x{v:02x}" for v in frame[row * width:(row + 1) * width]) + ",")
                lines.append("};")
            references.append(unique[key])
        lines.append(f"const ColorFrame {prefix}_frames[] PROGMEM = {{")
        lines.extend(f"  {{{symbol}, {duration}}}," for symbol, duration in zip(references, animation["durations"]))
        lines.append("};")
        lines.append(f'const char {prefix}_name[] PROGMEM = "{animation["name"]}";')
        entries.append(f"  {{{prefix}_name, {prefix}_frames, {len(references)}, {width}}},")
        lines.append("")
    if entries:
        lines.append("#define CUSTOM_MATRIX_ANIMATIONS \\")
        lines.extend(entry + (" \\" if i < len(entries) - 1 else "") for i, entry in enumerate(entries))
    else:
        lines.append("#define CUSTOM_MATRIX_ANIMATIONS")
    return "\n".join(lines) + "\n"


def atomic_write(path, content):
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    temporary = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=path.parent,
                                         delete=False, suffix=".tmp") as output:
            temporary = Path(output.name)
            output.write(content)
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def save_animation(value):
    animation = validate_animation(value)
    with SAVE_LOCK:
        animations = load_library()
        reserved = {a["name"] for a in animations + builtin_animations()} | {"off"}
        if animation["name"] in reserved:
            raise FileExistsError("That name already exists. Choose a new animation name.")
        animations.append(animation)
        check_budget(animations)
        header = render_header(animations)
        # Commit the canonical library first. Startup regenerates the header if interrupted.
        atomic_write(LIBRARY, json.dumps(animations, indent=2) + "\n")
        atomic_write(HEADER, header)
    return animation


class Handler(BaseHTTPRequestHandler):
    def setup(self):
        super().setup()
        self.connection.settimeout(10)

    def send_data(self, status, body, content_type="application/json; charset=utf-8"):
        if not isinstance(body, bytes):
            body = json.dumps(body).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(body)

    def valid_host(self):
        return self.headers.get("Host") in self.server.allowed_hosts

    def do_GET(self):
        if not self.valid_host():
            self.send_data(403, {"error": "Open the local URL printed in the launcher."})
            return
        path = self.path.split("?", 1)[0]
        if path == "/api/animations":
            try:
                self.send_data(200, {"animations": builtin_animations() + load_library()})
            except (OSError, ValueError, KeyError) as error:
                self.send_data(500, {"error": f"Could not read animation library: {error}"})
            return
        files = {"/": ("index.html", "text/html; charset=utf-8"),
                 "/app.js": ("app.js", "text/javascript; charset=utf-8"),
                 "/sprites.js": ("sprites.js", "text/javascript; charset=utf-8"),
                 "/style.css": ("style.css", "text/css; charset=utf-8")}
        if path == "/favicon.ico":
            self.send_data(204, b"")
        elif path in files:
            filename, content_type = files[path]
            self.send_data(200, (APP / filename).read_bytes(), content_type)
        else:
            self.send_data(404, {"error": "Not found."})

    def do_POST(self):
        origin = self.headers.get("Origin")
        if not self.valid_host() or (origin is not None and origin not in self.server.allowed_origins):
            self.send_data(403, {"error": "Save animations from the local Animation Studio tab."})
            return
        if self.path != "/api/animations":
            self.send_data(404, {"error": "Not found."})
            return
        if self.headers.get("Content-Type", "").split(";", 1)[0] != "application/json":
            self.send_data(415, {"error": "Send application/json."})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= MAX_BODY:
                self.send_data(413, {"error": "Upload must be between 1 byte and 512 KiB."})
                return
            value = json.loads(self.rfile.read(length))
            animation = save_animation(value)
            self.send_data(201, {"animation": animation, "message": "Added to project. Build and flash firmware to use it on your robots; restart the Go server to refresh its animation list."})
        except FileExistsError as error:
            self.send_data(409, {"error": str(error)})
        except (ValueError, UnicodeDecodeError) as error:
            self.send_data(400, {"error": str(error)})
        except OSError as error:
            self.send_data(500, {"error": f"Could not finish writing project files: {error}. Restart Studio to regenerate the firmware header from the saved library."})


def create_server(port):
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    actual_port = server.server_address[1]
    server.allowed_hosts = {f"127.0.0.1:{actual_port}", f"localhost:{actual_port}"}
    server.allowed_origins = {f"http://{host}" for host in server.allowed_hosts}
    return server


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8096)
    parser.add_argument("--no-browser", action="store_true")
    options = parser.parse_args()
    atomic_write(HEADER, render_header(load_library()))
    try:
        server = create_server(options.port)
    except OSError:
        if options.port != 8096:
            raise
        server = create_server(0)
    url = f"http://127.0.0.1:{server.server_address[1]}"
    print(f"\nAnimation Studio: {url}\nKeep this window open. Press Ctrl+C to stop.\n", flush=True)
    if not options.no_browser:
        threading.Timer(0.4, webbrowser.open, args=(url,)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nAnimation Studio stopped.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
